from ansi import AnsiColor, col

class BrightColor:
    BLACK = col(AnsiColor.BRIGHTBLACK)
    RED = col(AnsiColor.BRIGHTRED)
    GREEN = col(AnsiColor.BRIGHTGREEN)
    YELLOW = col(AnsiColor.BRIGHTYELLOW)
    BLUE = col(AnsiColor.BRIGHTBLUE)
    MAGENTA = col(AnsiColor.BRIGHTMAGENTA)
    CYAN = col(AnsiColor.BRIGHTCYAN)
    WHITE = col(AnsiColor.BRIGHTWHITE)
    DEFAULT = col(AnsiColor.DEFAULT)